import { createCanvas, DOMMatrix, ImageData, Path2D } from "@napi-rs/canvas";
globalThis.DOMMatrix = DOMMatrix; globalThis.ImageData = ImageData; globalThis.Path2D = Path2D;
const pdfjs = await import("pdfjs-dist/legacy/build/pdf.mjs");
const fs = await import("node:fs/promises");
const file = process.argv[2];
const data = new Uint8Array(await fs.readFile(file));
const doc = await pdfjs.getDocument({ data, useSystemFonts: false, isEvalSupported: false }).promise;
console.log("pages", doc.numPages);
const page = await doc.getPage(1);
const vp = page.getViewport({ scale: 1 });
console.log("size", vp.width, vp.height);
const scale = Math.min(2.5, 1400 / vp.width);
const vp2 = page.getViewport({ scale });
const canvas = createCanvas(Math.ceil(vp2.width), Math.ceil(vp2.height));
const ctx = canvas.getContext("2d");
ctx.fillStyle = "#fff"; ctx.fillRect(0,0,canvas.width,canvas.height);
await page.render({ canvasContext: ctx, viewport: vp2 }).promise;
const buf = await canvas.encode("png");
await fs.writeFile(process.argv[3], buf);
console.log("ok", buf.length);
